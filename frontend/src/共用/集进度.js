/* 统一的每集进度口径（全站唯一）：
   剧本 40%（该集有正文）+ 资产 20%（该集提取过资产）+ 分镜 40%（该集有分镜）。
   之前剧集详情页「分镜>0 直接 =100」与关卡详情页「+40」两条算法结果不一致，统一到这里。
   输入四组真库行（可传 null/undefined，缺哪组就当没有），输出 { 集号: 行 }。 */
export function 算每集进度(分集们, 剧本们, 资产全集, 分镜全集) {
  const 表 = {}
  const 集 = function (号) {
    if (!表[号]) {
      表[号] = { 集: 号, 标题: '', 状态: '未开始', 字数: 0, 资产: 0, 分镜: 0, 进度: 0 }
    }
    return 表[号]
  }
  ;(分集们 || []).forEach(function (行) {
    const 项 = 集(行.集号)
    项.标题 = 行.标题 || 项.标题
  })
  ;(剧本们 || []).forEach(function (行) {
    const 项 = 集(行.集号)
    项.字数 = 行.总字数 || 0
    if (项.字数 > 0) { 项.进度 += 40; 项.状态 = '剧本就绪' }
  })
  ;(资产全集 || []).forEach(function (行) {
    const 项 = 集(行.集号)
    项.资产++
  })
  ;(分镜全集 || []).forEach(function (行) {
    const 项 = 集(行.集号)
    项.分镜++
  })
  Object.keys(表).forEach(function (号) {
    const 项 = 表[号]
    if (项.资产 > 0) { 项.进度 += 20; if (项.状态 === '未开始') 项.状态 = '剧本就绪' }
    if (项.分镜 > 0) { 项.进度 += 40; 项.状态 = '分镜完成' }
  })
  return 表
}
