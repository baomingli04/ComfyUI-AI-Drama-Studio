// 任务页共用混入：3 秒轮询任务列表、媒体缩略图数据、放大预览、提示词扩写。
// 页面自身只需提供：data 表单/提交中，methods 拉任务列表/提交任务。
import { 取, 发, 基础地址, 取令牌 } from '@/接口/请求'
import { 媒体地址, 是图片, 是视频, 是音频 } from '@/接口/媒体'

// 每页扩写配置：模式 + 是否有扩写行（由页面覆盖 扩写模式）
export default {
  data() {
    return {
      任务列表: [],
      // 日志弹窗
      日志弹窗显示: false,
      当前日志: '',
      当前日志id: '',
      // 媒体预览
      预览显示: false,
      预览列表: [],
      预览索引: 0,
      // 扩写
      扩写模式: 'image',
      // 本页扩写下拉取哪个技能分类（技能分类.名称）。视频类页面用 minimax；
      // 图片类页面（T3 生成图片 / T3B 生成图片8K / 三图编辑一致版）覆盖为 图片提示词扩写
      扩写技能分类: 'minimax',
      技能列表: [],
      扩写技能id: '',
      扩写需求: '',
      扩写中: false
    }
  },
  computed: {
    上传地址() {
      return 基础地址 + '/api/上传'
    },
    上传头() {
      return { Authorization: 'Bearer ' + 取令牌() }
    },
    // ---- 按类型拆分的表单媒体列表 ----
    // 上面的 表单媒体列表() 把图/视频/音频混成一个列表，适合一页只有一类上传的页面。
    // 一页同时有「参考图 / 参考视频 / 参考音频」三个上传行时，每行必须只显示自己那一类，
    // 否则同一份素材会在多行里重复显示、删除也会删错行。
    // 这三个是按类型过滤后的同名列表，配下面的 删表单X媒体 用。
    表单图媒体列表() {
      const 列表 = []
      const 表单 = this.表单 || {}
      for (let i = 1; i <= 9; i++) {
        const 路径 = 表单['输入图' + i]
        if (路径 && 是图片(路径)) 列表.push({ 类型: 'image', 名称: '输入图' + i, 地址: 媒体地址(路径) })
      }
      return 列表
    },
    表单视频媒体列表() {
      const 列表 = []
      const 表单 = this.表单 || {}
      for (let i = 1; i <= 3; i++) {
        const 路径 = 表单['输入视频' + i]
        if (路径 && 是视频(路径)) 列表.push({ 类型: 'video', 名称: '输入视频' + i, 地址: 媒体地址(路径) })
      }
      return 列表
    },
    表单音频媒体列表() {
      const 列表 = []
      const 表单 = this.表单 || {}
      for (let i = 1; i <= 3; i++) {
        const 路径 = 表单['输入音频' + i]
        if (路径 && 是音频(路径)) 列表.push({ 类型: 'audio', 名称: '输入音频' + i, 地址: 媒体地址(路径) })
      }
      return 列表
    }
  },
  created() {
    this.拉任务列表()
    this._轮询定时器 = setInterval(() => {
      // 页面不可见时不打扰后端
      if (!document.hidden) this.拉任务列表()
    }, 3000)
    this.拉技能列表()
  },
  beforeDestroy() {
    if (this._轮询定时器) clearInterval(this._轮询定时器)
  },
  methods: {
    // ---- 媒体 ----
    输入媒体(行) {
      const 列表 = []
      for (let i = 1; i <= 9; i++) {
        const 路径 = 行['输入图' + i]
        if (路径 && 是图片(路径)) 列表.push({ 类型: 'image', 名称: '输入图' + i, 地址: 媒体地址(路径) })
      }
      for (let i = 1; i <= 3; i++) {
        const 路径 = 行['输入视频' + i]
        if (路径 && 是视频(路径)) 列表.push({ 类型: 'video', 名称: '输入视频' + i, 地址: 媒体地址(路径) })
      }
      for (let i = 1; i <= 3; i++) {
        const 路径 = 行['输入音频' + i]
        if (路径 && 是音频(路径)) 列表.push({ 类型: 'audio', 名称: '输入音频' + i, 地址: 媒体地址(路径) })
      }
      return 列表
    },
    产物媒体(行) {
      const 列表 = []
      if (行.产物图片 && 是图片(行.产物图片)) {
        列表.push({ 类型: 'image', 名称: '产物图片', 地址: 媒体地址(行.产物图片) })
      }
      // 第 2 张：文生图8K（1x 原尺寸 + 4x 放大）、多图编辑多人合并版 / 三图编辑一致版（成品 + SeedVR2 放大）
      if (行.产物图片2 && 是图片(行.产物图片2)) {
        列表.push({ 类型: 'image', 名称: '产物图片2', 地址: 媒体地址(行.产物图片2) })
      }
      // 两张产物时标出哪张是哪张：表格缩略图左下角角标 + 预览弹窗标题
      if (列表.length === 2) {
        列表[0].角标 = 列表[0].名称 = '原图'
        列表[1].角标 = 列表[1].名称 = '放大后'
      }
      for (const 键 of ['产物视频1', '产物视频2']) {
        if (行[键] && 是视频(行[键])) 列表.push({ 类型: 'video', 名称: 键, 地址: 媒体地址(行[键]) })
      }
      return 列表
    },
    打开预览(行, 索引) {
      this.预览列表 = this.输入媒体(行).concat(this.产物媒体(行))
      this.预览索引 = 索引 || 0
      this.预览显示 = true
    },
    // 表单里已上传的媒体（上传后立刻可见，不用等任务列表）
    表单媒体列表() {
      const 列表 = []
      const 表单 = this.表单 || {}
      for (let i = 1; i <= 9; i++) {
        if (表单['输入图' + i] && 是图片(表单['输入图' + i])) {
          列表.push({ 类型: 'image', 名称: '输入图' + i, 地址: 媒体地址(表单['输入图' + i]) })
        }
      }
      for (let i = 1; i <= 3; i++) {
        if (表单['输入视频' + i] && 是视频(表单['输入视频' + i])) {
          列表.push({ 类型: 'video', 名称: '输入视频' + i, 地址: 媒体地址(表单['输入视频' + i]) })
        }
      }
      for (let i = 1; i <= 3; i++) {
        if (表单['输入音频' + i] && 是音频(表单['输入音频' + i])) {
          列表.push({ 类型: 'audio', 名称: '输入音频' + i, 地址: 媒体地址(表单['输入音频' + i]) })
        }
      }
      return 列表
    },
    预览表单媒体() {
      this.预览列表 = this.表单媒体列表()
      this.预览索引 = 0
      this.预览显示 = true
    },
    // ---- 表单区缩略图逐条删除 ----
    // 组件 emit('删除', 下标)，下标是 表单媒体列表() 显示列表里的位置。
    // 显示列表每项带 名称（'输入图3' / '输入视频2' / '输入音频1'），按名字定位槽位。
    // 两个版本按页面槽位语义选：
    //   删表单媒体     —— 只清该槽，不前移。角色位页用它（三图编辑的 图1=主图、
    //                      首尾帧的 图1=首帧/图2=尾帧、人物替换的 底图/人物图）：
    //                      删了中间一张不能把后面的顶上来，语义会变。
    //   删表单媒体顺移 —— 清该槽 + 同类后续素材依次前移，保持 1..N 连续。
    //                      顺序位页用它（多参考/参考生视频/二采重绘的 输入图1~9）：
    //                      中间留空槽会让编号和实际素材对不上。
    删表单媒体(下标) {
      const 名 = ((this.表单媒体列表())[下标] || {}).名称 || ''
      const m = /^输入(图|视频|音频)(\d+)$/.exec(名)
      if (!m) return
      this.$set(this.表单, '输入' + m[1] + m[2], '')
    },
    删表单媒体顺移(下标) {
      const 名 = ((this.表单媒体列表())[下标] || {}).名称 || ''
      const m = /^输入(图|视频|音频)(\d+)$/.exec(名)
      if (!m) return
      const 前缀 = '输入' + m[1]
      const 个数 = m[1] === '图' ? 9 : 3
      const 值 = []
      for (let i = 1; i <= 个数; i++) if (this.表单[前缀 + i]) 值.push(this.表单[前缀 + i])
      值.splice(Number(m[2]) - 1, 1)
      for (let i = 1; i <= 个数; i++) this.$set(this.表单, 前缀 + i, 值[i - 1] || '')
    },
    // ---- 按类型删除（配 表单图/视频/音频媒体列表） ----
    // 下标就是那一行自己列表里的位置，删掉后同类后续素材依次前移，
    // 保持 1..N 连续（参考图/参考视频/参考音频 都是顺序位：编号即上传顺序）。
    删表单图媒体(下标) {
      this._删表单类型前移('图', 9, 下标)
    },
    删表单视频媒体(下标) {
      this._删表单类型前移('视频', 3, 下标)
    },
    删表单音频媒体(下标) {
      this._删表单类型前移('音频', 3, 下标)
    },
    _删表单类型前移(类型, 个数, 下标) {
      const 前缀 = '输入' + 类型
      const 值 = []
      for (let i = 1; i <= 个数; i++) if (this.表单[前缀 + i]) 值.push(this.表单[前缀 + i])
      值.splice(Number(下标), 1)
      for (let i = 1; i <= 个数; i++) this.$set(this.表单, 前缀 + i, 值[i - 1] || '')
    },
    预览切换(步进) {
      const 总数 = this.预览列表.length
      if (!总数) return
      this.预览索引 = (this.预览索引 + 步进 + 总数) % 总数
    },
    // ---- 扩写 ----
    async 拉技能列表() {
      try {
        const 数据 = await 取('/api/提示词/技能列表?分类=' + encodeURIComponent(this.扩写技能分类))
        this.技能列表 = 数据.列表 || []
        // 默认选第一个（后端按 id 升序返回）；已选过就不覆盖
        if (!this.扩写技能id && this.技能列表.length) {
          this.扩写技能id = this.技能列表[0].id
        }
      } catch (e) {
        /* 技能列表拉不到不阻塞页面 */
      }
    },
    // 附加规则 = 本页「扩写提示词配置」里的规则，由扩写行随事件带过来，原样发给后端
    async 扩写(附加规则) {
      if (!this.扩写技能id) {
        this.$message.warning('请先选择提示词技能')
        return
      }
      if (!this.扩写需求 || !this.扩写需求.trim()) {
        this.$message.warning('请先填写扩写需求')
        return
      }
      this.扩写中 = true
      try {
        // 引用 = 表单里已填的输入媒体（按 图N/视频N/音频N 顺序命名），
        // 用户上传什么就报什么，后端按这些数量生成 @图N/@视频N/@音频N 锚点
        const 引用 = []
        for (let i = 1; i <= 9; i++) {
          if (this.表单['输入图' + i]) 引用.push({ 名称: '图' + i, 类型: 'image' })
        }
        for (let i = 1; i <= 3; i++) {
          if (this.表单['输入视频' + i]) 引用.push({ 名称: '视频' + i, 类型: 'video' })
        }
        for (let i = 1; i <= 3; i++) {
          if (this.表单['输入音频' + i]) 引用.push({ 名称: '音频' + i, 类型: 'audio' })
        }
        const 请求体 = {
          技能id: this.扩写技能id,
          模式: this.扩写模式,
          需求: this.扩写需求.trim(),
          引用,
          附加规则: 附加规则 || ''
        }
        // 页面有「生成声音」这类开关时，用 扩写声音模式 计算属性告诉后端怎么写声音字段
        // （不传时后端按 dialogue_only 处理，其它页面行为不变）
        if (this.扩写声音模式) 请求体.声音模式 = this.扩写声音模式
        const 数据 = await 发('/api/提示词/扩写', 请求体)
        this.$set(this.表单, '正向提示词', 数据.提示词 || '')
        this.$message.success('已扩写并填入正向提示词')
      } catch (e) {
        this.报错(e)
      } finally {
        this.扩写中 = false
      }
    },
    // ---- 日志 / 取消 ----
    async 查看日志(行) {
      try {
        const 数据 = await 取('/api/任务/日志?id=' + 行.id)
        this.当前日志 = 数据.日志
        this.当前日志id = 行.id
        this.日志弹窗显示 = true
      } catch (e) {
        this.报错(e)
      }
    },
    async 取消任务(行) {
      try {
        await 发('/api/任务/取消', { id: 行.id })
        this.$message.success('已取消')
        this.拉任务列表()
      } catch (e) {
        this.报错(e)
      }
    },
    // 删终态任务：库行 + 该任务的产物文件一起删（输入素材不删）。二次确认，不可恢复。
    async 删除任务(行) {
      try {
        await this.$confirm('删除任务 #' + 行.id + '？该任务的产物文件会一起删掉，不可恢复。', '提示', { type: 'warning' })
      } catch (e) {
        return
      }
      try {
        await 发('/api/任务/删除', { id: 行.id })
        this.$message.success('已删除')
        this.拉任务列表()
      } catch (e) {
        this.报错(e)
      }
    },
    // 终态（成功/失败/中断/已取消）→ 操作列给「删除」；过程态还在跑 → 给「取消」
    是终态(行) {
      return ['成功', '失败', '中断', '已取消'].indexOf(行.状态) >= 0
    },
    报错(e) {
      this.$message.error(e.message)
      if (e.状态码 === 401) {
        this.$router.push('/login')
      }
    }
  }
}
