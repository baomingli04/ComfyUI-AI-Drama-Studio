/* 进页面换一个新种子（对齐后端 随机种子() 区间 0~2^48，与 /test/d-all 同规则） */
export function 新种子() {
  return Math.floor(Math.random() * 2 ** 48)
}

/* 比例 + 一采MP → 32 倍数宽高（与 T8/D2/D-all 工作流节点同公式，只用于提交宽高与显示） */
export function 算画布(比例, mp) {
  const 比例表 = {
    '1:1': [1, 1], '2:3': [2, 3], '3:2': [3, 2], '3:4': [3, 4],
    '4:3': [4, 3], '9:16': [9, 16], '16:9': [16, 9], '21:9': [21, 9]
  }
  const 比 = 比例表[String(比例 || '').trim()]
  if (!比) return null
  const 值 = Math.min(16, Math.max(0.1, Number(mp) || 0.4))
  const 缩放 = Math.sqrt((值 * 1024 * 1024) / (比[0] * 比[1]))
  const 对齐 = function (n) { return Math.round(n / 32) * 32 }
  return { 宽: 对齐(比[0] * 缩放), 高: 对齐(比[1] * 缩放) }
}

/* '3s' → 3；解析不出回退 默认 */
export function 取镜秒(时长文本, 默认) {
  const 配 = /(\d+(?:\.\d+)?)/.exec(String(时长文本 || ''))
  const 秒 = 配 ? Math.round(parseFloat(配[1])) : 0
  return Math.min(15, Math.max(1, 秒 || (默认 || 5)))
}

/* 拼任务参数：逐字段对齐四个原页面（/test/d-all · d2-r2v · t8-ref2video · t10-repaint）的提交体，只能多不能少。
   槽 = { 首帧, 尾帧, 源视频, 参考图们:[url], 参考视频们:[url], 参考音频们:[url], 提示词, 反向提示词 }
   配 = { 比例, 一采MP, 二采MP, 时长, seed, cfg, 步数, 采样器, 生成声音, 底膜精度 } */
export function 拼任务参数(方式键, 槽, 配) {
  const 元 = 方式表[方式键]
  if (!元) throw new Error('未知生成方式：' + 方式键)
  const 配值 = 配 || {}
  const 图们 = (槽.参考图们 || []).filter(function (u) { return u })
  const 视频们 = (槽.参考视频们 || []).filter(function (u) { return u })
  const 音频们 = (槽.参考音频们 || []).filter(function (u) { return u })
  const 参数 = {}

  if (元.类型 === '导演台全能') {
    /* /test/d-all：Object.assign({类型}, 表单) 全量提交，空槽位删掉 */
    参数.类型 = '导演台全能'
    参数.模式 = 元.模式
    参数.正向提示词 = (槽.提示词 || '').trim()
    参数.反向提示词 = String(槽.反向提示词 == null ? '' : 槽.反向提示词).trim() || 'bad video'
    const 种子数 = Number(配值.seed)
    参数.seed = (配值.seed == null || 配值.seed === '' || isNaN(种子数)) ? 新种子() : 种子数
    参数.cfg = 配值.cfg == null ? 1 : 配值.cfg
    参数.比例 = 配值.比例 || '16:9'
    参数.一采MP = 配值.一采MP || 0.4
    参数.视频时长 = 配值.时长 || 15
    参数.生成声音 = !!配值.生成声音
    参数.步数 = 配值.步数 || 8
    参数.采样器 = 配值.采样器 || 'res_multistep'
    参数.底膜精度 = 配值.底膜精度 || 'int8'
    const 画 = 算画布(参数.比例, 参数.一采MP)
    参数.视频宽 = 画 ? 画.宽 : 0
    参数.视频高 = 画 ? 画.高 : 0
    if (元.模式 === 'i2v') 参数.输入图1 = 槽.首帧 || ''
    if (元.模式 === 'fl2v') { 参数.输入图1 = 槽.首帧 || ''; if (槽.尾帧) 参数.输入图2 = 槽.尾帧 }
    if (元.模式 === 'r2v') {
      图们.forEach(function (u, i) { 参数['输入图' + (i + 1)] = u })
      视频们.forEach(function (u, i) { 参数['输入视频' + (i + 1)] = u })
      音频们.forEach(function (u, i) { 参数['输入音频' + (i + 1)] = u })
    }
    if (元.模式 === 'v2v') 参数.输入视频1 = 槽.源视频 || ''
    if (元.模式 === 'rv2v') {
      参数.输入视频1 = 槽.源视频 || ''
      图们.forEach(function (u, i) { 参数['输入图' + (i + 1)] = u })
      音频们.forEach(function (u, i) { 参数['输入音频' + (i + 1)] = u })
    }
    /* t2v 无素材槽 */
  } else if (元.类型 === '多参考生视频') {
    /* /test/d2-r2v：参考图≤9 + 参考视频≤3 + 参考音频≤3 + 正/反向 + 比例/一采MP/时长 + seed/cfg + 宽高 */
    参数.类型 = '多参考生视频'
    参数.正向提示词 = (槽.提示词 || '').trim()
    参数.反向提示词 = String(槽.反向提示词 == null ? '' : 槽.反向提示词).trim()
    参数.seed = 配值.seed == null ? '' : 配值.seed
    参数.cfg = 配值.cfg == null ? 1 : 配值.cfg
    参数.比例 = 配值.比例 || '9:16'
    参数.一采MP = 配值.一采MP || 0.4
    参数.视频时长 = 配值.时长 || 5
    const 画 = 算画布(参数.比例, 参数.一采MP)
    参数.视频宽 = 画 ? 画.宽 : 480
    参数.视频高 = 画 ? 画.高 : 864
    图们.slice(0, 9).forEach(function (u, i) { 参数['输入图' + (i + 1)] = u })
    视频们.slice(0, 3).forEach(function (u, i) { 参数['输入视频' + (i + 1)] = u })
    音频们.slice(0, 3).forEach(function (u, i) { 参数['输入音频' + (i + 1)] = u })
  } else if (元.类型 === '参考生视频') {
    /* /test/t8：参考图≤9 + 参考视频≤3 + 参考音频≤3 + 正向 + 比例/一采MP(可空)/时长；宽高由工作流算，不提交 */
    参数.类型 = '参考生视频'
    参数.正向提示词 = (槽.提示词 || '').trim()
    参数.比例 = 配值.比例 || '16:9'
    if (配值.一采MP !== '' && 配值.一采MP != null) 参数.一采MP = 配值.一采MP
    参数.视频时长 = 配值.时长 || 5
    图们.slice(0, 9).forEach(function (u, i) { 参数['输入图' + (i + 1)] = u })
    视频们.slice(0, 3).forEach(function (u, i) { 参数['输入视频' + (i + 1)] = u })
    音频们.slice(0, 3).forEach(function (u, i) { 参数['输入音频' + (i + 1)] = u })
  } else if (元.类型 === '二采重绘') {
    /* /test/t10：源视频(输入视频1) + 参考图≤8 + 参考音频≤3 + 正向 + 一采MP/二采MP/比例/时长 */
    参数.类型 = '二采重绘'
    参数.输入视频1 = 槽.源视频 || ''
    参数.正向提示词 = (槽.提示词 || '').trim()
    参数.一采MP = 配值.一采MP || ''
    参数.二采MP = 配值.二采MP || ''
    参数.比例 = 配值.比例 || '16:9'
    参数.视频时长 = 配值.时长 || 7
    图们.slice(0, 8).forEach(function (u, i) { 参数['输入图' + (i + 1)] = u })
    音频们.slice(0, 3).forEach(function (u, i) { 参数['输入音频' + (i + 1)] = u })
  }

  /* 空槽位不提交（后端按有值的连续段填参考位、其余柔性摘除） */
  for (let i = 1; i <= 9; i++) if (!参数['输入图' + i]) delete 参数['输入图' + i]
  for (let i = 1; i <= 3; i++) if (!参数['输入视频' + i]) delete 参数['输入视频' + i]
  for (let i = 1; i <= 3; i++) if (!参数['输入音频' + i]) delete 参数['输入音频' + i]
  return 参数
}

/* 方式校验：缺什么素材直接报文案，返回 '' 表示通过（对齐各原页提交前的校验） */
export function 校验方式(方式键, 槽) {
  const 元 = 方式表[方式键]
  if (!元) return '未知生成方式'
  const 图数 = (槽.参考图们 || []).filter(function (u) { return u }).length
  const 有提示词 = !!(槽.提示词 || '').trim()
  if (元.类型 === '导演台全能') {
    const 模式 = 元.模式
    if (模式 === 'r2v' && !图数) return '参考主体请先挂至少 1 张参考图（资源区标注「参考」）'
    if (模式 === 'i2v' && !槽.首帧) return '图生视频请先在本镜资源区标注一张「首帧」'
    if (模式 === 'fl2v' && !槽.首帧) return '首尾帧请先标注「首帧」（可再标「尾帧」）'
    if ((模式 === 'v2v' || 模式 === 'rv2v') && !槽.源视频) return '请先选一版已生成的视频作源视频'
    if (模式 === 't2v' && !有提示词) return '文生视频请输入正向提示词'
    if ((模式 === 'v2v' || 模式 === 'rv2v') && !有提示词) return '要写清「改成什么样」，请输入正向提示词'
    return ''
  }
  if (方式键 === '二采重绘') {
    if (!槽.源视频) return '二采重绘要先选一版已生成的视频作源视频'
    return ''
  }
  if (元.需要 === '参考图' && !图数) return '请先挂至少 1 张参考图（资源区标注「参考」）'
  return ''
}

/* 智能推荐：镜 + 该镜资源图们 + 是否已有生成视频 → 推荐方式键
   规则：已有视频=二采重绘（改片最常用）；有首帧标注图=图生视频；
        画面里认出 ≥2 个资产名=多参考；认出 1 个=参考生视频；兜底=图生视频（有图）/文生视频 */
export function 推荐方式(镜, 图们, 资产命中数, 有选中版) {
  if (有选中版) return '二采重绘'
  const 有首帧 = (图们 || []).some(function (图) { return (图.标注 || '') === '首帧' }) || !!(镜 && 镜.首帧url)
  if (有首帧) return '图生视频'
  if (资产命中数 >= 2) return '多参考生视频'
  if (资产命中数 === 1) return '参考生视频'
  if ((图们 || []).length) return '图生视频'
  return '文生视频'
}

/* 画面描述里认资产名（名称全含 / 别名段全含），返回命中的资产行们 */
export function 匹配资产(画面文本, 资产行们) {
  const 文 = String(画面文本 || '')
  const 命中 = []
  for (let i = 0; i < (资产行们 || []).length; i++) {
    const 行 = 资产行们[i]
    const 词们 = [行.名称].concat(String(行.别名 || '').split(/[、,，/]/))
    for (let j = 0; j < 词们.length; j++) {
      const 词 = String(词们[j] || '').trim()
      if (词 && 词.length >= 2 && 文.indexOf(词) >= 0) { 命中.push(行); break }
    }
  }
  return 命中
}

/* 按画面文本里的【形态名】从资产的图们里选图：画面写了「李宝明【战斗装】」就优先挂战斗装那张
   （图.形态 或 图.标注 命中形态名）。匹配顺序：当前图 → 全部图（含历史，画面点名了就给对形态）
   → 没写形态或没匹配到 → 第一张当前图。返回图行（可能 null）。
   替代"无脑取第一张当前图"——一人多套服装时镜头要挂对形态，否则人物不伦不类 */
export function 选形态图(行, 画面文本) {
  const 图们 = ((行 && 行.图们) || []).filter(function (g) { return g && g.url })
  if (!图们.length) return null
  const 当前们 = 图们.filter(function (g) { return (g.状态 || '当前') === '当前' })
  const 文 = String(画面文本 || '')
  const 配们 = 文.match(/【([^】]{1,20})】/g) || []
  for (let i = 0; i < 配们.length; i++) {
    const 名 = 配们[i].slice(1, -1).trim()
    if (!名) continue
    const 按名 = function (池) { return 池.filter(function (g) { return (g.形态 || '') === 名 || (g.标注 || '') === 名 })[0] }
    const 命中 = 按名(当前们) || 按名(图们)
    if (命中) return 命中
  }
  return 当前们[0] || 图们[0]
}

/* 提示词草稿：景别/运镜 + 画面 + 台词 */
export function 提示词草稿(镜) {
  if (!镜) return ''
  const 段 = []
  const 头 = [(镜.景别 || ''), (镜.运镜 || '')].filter(function (x) { return x && x !== '—' }).join('，')
  if (头) 段.push(头)
  段.push(String(镜.画面 || '').trim())
  const 词 = String(镜.台词 || '').trim()
  if (词 && 词 !== '（无）') 段.push('人物开口：「' + 词 + '」，口型与情绪对上台词')
  return 段.join('。')
}

/* ---------- 生成中版本的回写（提交时就落「生成中」行，出片后对着任务表补 url） ---------- */

const 终态们 = ['成功', '失败', '中断', '已取消']

/* 对账：查任务表，把还能推进的「生成中」版本算出来。
   返回 [{版本id, 镜号, 状态:'已生成'|'失败', url}]，由调用方逐条 POST /api/分镜/视频保存 落库 */
export async function 对账生成中版本(版本们) {
  const 未完 = (版本们 || []).filter(function (v) { return v.状态 === '生成中' && v.任务id })
  if (!未完.length) return []
  const 类型们 = {}
  未完.forEach(function (v) {
    const 元 = 方式表[v.方式]
    if (元) 类型们[元.类型] = 1
  })
  const 任务映射 = {}
  const 类型键们 = Object.keys(类型们)
  for (let i = 0; i < 类型键们.length; i++) {
    try {
      const 数据 = await 取('/api/任务列表?类型=' + encodeURIComponent(类型键们[i]) + '&条数=100')
      ;((数据 && 数据.列表) || []).forEach(function (行) { 任务映射[行.id] = 行 })
    } catch (e) { /* 拉不到这轮先跳过 */ }
  }
  const 结果 = []
  未完.forEach(function (v) {
    const 行 = 任务映射[v.任务id]
    if (!行) return
    if (行.状态 === '成功') {
      const url = 行.产物视频1 || 行.产物视频2 || ''
      if (url) 结果.push({ 版本id: v.id, 镜号: v.镜号, 状态: '已生成', url: url })
      else 结果.push({ 版本id: v.id, 镜号: v.镜号, 状态: '失败' })
    } else if (终态们.indexOf(行.状态) >= 0) {
      结果.push({ 版本id: v.id, 镜号: v.镜号, 状态: '失败' })
    }
  })
  return 结果
}

/* 把一条对账结果落库 */
export function 落对账结果(剧id, 集号, 镜号, 项) {
  if (项.状态 === '已生成') {
    return 发('/api/分镜/视频保存', { 剧id: 剧id, 集号: 集号, 镜号: 镜号, 动作: '完成', id: 项.版本id, url: 项.url })
  }
  return 发('/api/分镜/视频保存', { 剧id: 剧id, 集号: 集号, 镜号: 镜号, 动作: '失败', id: 项.版本id })
}

